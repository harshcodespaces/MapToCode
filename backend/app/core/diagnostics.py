DIAGNOSTIC_RULE_VERSION = "1.0.0"


def create_diagnostic(
    code: str,
    category: str,
    message: str,
    severity: str = "error",
    source_refs: Optional[List[Dict[str, Any]]] = None,
    suggestion: Optional[str] = None,
) -> Dict[str, Any]:
    if code not in DIAGNOSTIC_CODES:
        raise ValueError(f"Unknown diagnostic code: {code}")
    if not category or not message:
        raise ValueError("A diagnostic needs a category and message.")
    
    diag: Dict[str, Any] = {
        "code": code,
        "severity": severity,
        "category": category,
        "message": message,
        "sourceRefs": source_refs if source_refs is not None else [],
        "ruleVersion": DIAGNOSTIC_RULE_VERSION,
    }
    if suggestion:
        diag["suggestion"] = suggestion
    return diag
